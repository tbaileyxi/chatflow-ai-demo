// Generates the team pages that aren't hand-written.
//
// src/lib/teams.ts holds 19 teams somebody typed out by hand — real brand
// colours, real chapter counts. This script covers the rest: every team whose
// public room has actually said something lately, pulled straight from the
// database so the page list can't drift from the rooms that exist.
//
// Run it when rooms wake up:  node scripts/gen-team-pages.mjs
// It rewrites src/lib/teams.generated.ts and public/sitemap.xml. Both are
// committed — the site is static, so nothing is fetched at request time.

import { writeFileSync, readFileSync } from "node:fs";

// PAUSED (2026-09-19): every /t/* URL 301s to / (vercel.json) and the team
// pages are out of the footer and the sitemap. Running this would put 181
// redirecting URLs back in the sitemap. Remove the redirect first.
if (!process.env.FORCE_TEAM_PAGES) {
  console.error("Team pages are redirected to / right now (vercel.json). Remove that rule, then run with FORCE_TEAM_PAGES=1.");
  process.exit(1);
}

const URL_BASE = "https://dejuwyeypiggvlyfliap.supabase.co";
const KEY = (readFileSync("src/integrations/supabase/client.ts", "utf8")
  .match(/eyJ[A-Za-z0-9_.-]{60,}/) || [])[0];
if (!KEY) throw new Error("no anon key in src/integrations/supabase/client.ts");

const api = async (path) => {
  const r = await fetch(`${URL_BASE}/rest/v1/${path}`, {
    headers: { apikey: KEY, Authorization: `Bearer ${KEY}` },
  });
  if (!r.ok) throw new Error(`${path} -> ${r.status} ${await r.text()}`);
  return r.json();
};

// A page is worth indexing only if the room behind it has something on it.
// An empty room is a thin page, and thin pages teach Google that this whole
// section is low value — worse than not having the page at all.
const SINCE = new Date(Date.now() - 21 * 864e5).toISOString().slice(0, 10);

const [rooms, recent] = await Promise.all([
  api("huddles?select=id,team_id,is_private&is_private=eq.false&limit=1000"),
  api(`huddle_messages?select=huddle_id&created_at=gte.${SINCE}&limit=20000`),
]);

const live = new Set(recent.map((m) => m.huddle_id));
const teamIds = new Set(
  rooms.filter((r) => r.team_id && live.has(r.id)).map((r) => r.team_id),
);

const teams = (
  await api("teams?select=id,name,city,league,logo_url,status&status=eq.active&limit=1000")
).filter((t) => teamIds.has(t.id) && t.city && t.name);

const kebab = (s) =>
  s.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "");

// College teams are known by the school ("penn-state"), pro teams by city plus
// nickname ("cleveland-browns"). Matching that split keeps the generated slugs
// in the same shape as the hand-written ones people already link to.
const college = (t) => String(t.league || "").startsWith("NCAA");
const baseSlug = (t) => (college(t) ? kebab(t.city) : kebab(`${t.city} ${t.name}`));

const curated = [...readFileSync("src/lib/teams.ts", "utf8")
  .matchAll(/^\s*'([a-z0-9-]+)':\s*\{/gm)].map((m) => m[1]);

const seen = new Set(curated);
const out = [];
for (const t of teams.sort((a, b) => `${a.city}${a.name}`.localeCompare(`${b.city}${b.name}`))) {
  let slug = baseSlug(t);
  if (seen.has(slug)) {
    // Two Miamis, two USCs. Fall back to the mascot rather than a number —
    // "miami-hurricanes" is a URL a person can read and a search can match.
    slug = kebab(`${t.city} ${t.name}`);
    if (seen.has(slug)) continue;
  }
  seen.add(slug);
  out.push({
    slug,
    name: `${t.city} ${t.name}`.trim(),
    short: t.city,
    league: t.league,
    logo: t.logo_url || "",
  });
}

const today = new Date().toISOString().slice(0, 10);

writeFileSync(
  "src/lib/teams.generated.ts",
  `// GENERATED by scripts/gen-team-pages.mjs — do not edit by hand.
// Teams whose public room was active in the 21 days before ${today}.
// Hand-written teams live in teams.ts and win on any slug collision.

export type GeneratedTeam = {
  slug: string;
  name: string;
  short: string;
  league: string;
  logo: string;
};

export const GENERATED_TEAMS: GeneratedTeam[] = ${JSON.stringify(out, null, 2)};
`,
);

// The sitemap is the only thing telling Google these pages exist, so it is
// written from the same list in the same run. Two hand-maintained copies would
// drift, and a sitemap listing a page that 404s is worse than a short sitemap.
const STATIC = [
  ["", "daily", "1.0"],
  ["faq", "monthly", "0.6"],
  ["contact", "yearly", "0.4"],
  ["privacy", "yearly", "0.3"],
  ["teams", "weekly", "0.8"],
];
const url = (path, freq, pri) =>
  `  <url>\n    <loc>https://www.sidehuddlesports.com/${path}</loc>\n` +
  `    <lastmod>${today}</lastmod>\n    <changefreq>${freq}</changefreq>\n` +
  `    <priority>${pri}</priority>\n  </url>`;

writeFileSync(
  "public/sitemap.xml",
  `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
    [
      ...STATIC.map(([p, f, pr]) => url(p, f, pr)),
      ...curated.map((s) => url(`t/${s}`, "daily", "0.7")),
      ...out.map((t) => url(`t/${t.slug}`, "daily", "0.6")),
    ].join("\n") +
    `\n</urlset>\n`,
);

console.log(`generated ${out.length} team pages (${curated.length} hand-written kept)`);
console.log(`sitemap: ${STATIC.length + curated.length + out.length} urls`);
console.log(out.slice(0, 6).map((t) => `  /t/${t.slug} -> ${t.name}`).join("\n"));
